#!/usr/bin/env node
// Concatenates src/app/*.js (in filename order) into public/app.js inside one IIFE, then
// stamps index.html with a content hash so a changed bundle is always fetched fresh and
// the in-app update banner still fires. No dependencies, no transforms: the bundle is
// the source files joined in order, so what runs is what you wrote.
//
// It also stamps the service worker's cache name. That used to be bumped by hand, which
// is exactly the step that gets forgotten: change an icon or the manifest, deploy, and
// every installed app keeps serving the old one out of a cache nobody invalidated. The
// name is now a hash of the files the worker actually precaches, so it moves by itself
// when one of them does and stays put when none of them have.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const sha = (s) => crypto.createHash("sha256").update(s).digest("hex").slice(0, 10);

/** The worker's own SHELL list, resolved to files on disk. One source of truth: the list
 *  the worker caches is the list the version is computed from, so they cannot drift. */
function shellFiles(root = __dirname) {
  const sw = fs.readFileSync(path.join(root, "public", "sw.js"), "utf8");
  const m = sw.match(/^const SHELL = (\[[^\]]*\]);$/m);
  if (!m) throw new Error("sw.js has no `const SHELL = [...]` line to read");
  return JSON.parse(m[1]).map((url) => ({
    url,
    // "/" is index.html; everything else is its own path under public/.
    file: path.join(root, "public", url === "/" ? "index.html" : url),
  }));
}

/** Cache name for the service worker: a hash of everything it precaches. */
function shellVersion(root = __dirname) {
  const parts = shellFiles(root).map(({ url, file }) => {
    if (!fs.existsSync(file)) throw new Error(`sw.js precaches ${url}, but ${path.relative(root, file)} does not exist`);
    return url + ":" + sha(fs.readFileSync(file));
  });
  return "ob-" + sha(parts.join("\n"));
}

function stampServiceWorker(root = __dirname) {
  const p = path.join(root, "public", "sw.js");
  const before = fs.readFileSync(p, "utf8");
  const version = shellVersion(root);
  const after = before.replace(/^const VERSION = "[^"]*";$/m, `const VERSION = "${version}";`);
  if (!after.includes(`const VERSION = "${version}";`)) throw new Error("sw.js has no `const VERSION = \"…\";` line to stamp");
  if (after !== before) fs.writeFileSync(p, after);
  return version;
}

/** The Guide, as the coach reads it: the rendered HTML flattened to headed text.
 *  Headings keep their level, folds become headings, lists become lines. */
function htmlToText(html) {
  const ent = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", rarr: "\u2192", larr: "\u2190", middot: "\u00b7", ndash: "\u2013", mdash: "\u2014", times: "\u00d7", hellip: "\u2026", deg: "\u00b0" };
  return html
    .replace(/<(svg|button|script|style)\b[^>]*>[\s\S]*?<\/\1>/g, "")
    .replace(/<h2\b[^>]*>/g, "\n\n# ").replace(/<h3\b[^>]*>/g, "\n\n## ")
    .replace(/<summary\b[^>]*>/g, "\n\n### ").replace(/<\/summary>/g, "\n")
    .replace(/<li\b[^>]*>/g, "\n- ").replace(/<dt\b[^>]*>/g, "\n").replace(/<dd\b[^>]*>/g, ": ")
    .replace(/<span class="(?:chip|mono small)[^"]*"[^>]*>([^<]*)<\/span>/g, " ($1)").replace(/<span\b[^>]*>/g, " ")
    .replace(/<(td|th)\b[^>]*>/g, " | ").replace(/<br\b[^>]*>/g, "\n")
    .replace(/<(p|div|details|ul|ol|dl|tr|table|h2|h3|h4|section)\b[^>]*>/g, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, c) => c[0] === "#"
      ? String.fromCodePoint(c[1].toLowerCase() === "x" ? parseInt(c.slice(2), 16) : +c.slice(1))
      : (ent[c.toLowerCase()] ?? m))
    .replace(/[ \t]+/g, " ").replace(/ *\n */g, "\n").replace(/\n{3,}/g, "\n\n").trim();
}

/** Renders the Guide out of the bundle just written and saves it as an ES module the
 *  Worker imports, so the coach reads the same Guide the person does. The bundle is
 *  loaded through the test harness, since that is the one thing here that can run the
 *  app without a browser. Returns the text's length. */
function writeGuide(root = __dirname) {
  const { loadApp } = require("./test/harness.js");
  const text = htmlToText(loadApp({ root }).vGuideHtml());
  if (text.length < 20000) throw new Error("the Guide rendered to almost nothing");
  const out = `// Generated by build.js from the app's Guide (vGuideHtml in src/app/21-programs.js).\n` +
    `// The coach reads this. Do not edit here: change the Guide and build.\n` +
    `export const GUIDE_TEXT = ${JSON.stringify(text)};\n`;
  const p = path.join(root, "src", "guide-text.js");
  if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== out) fs.writeFileSync(p, out);
  return text.length;
}

function build(root = __dirname) {
  const srcDir = path.join(root, "src", "app");
  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith(".js")).sort();
  if (!files.length) throw new Error("no source files in src/app");

  const body = files
    .map((f) => fs.readFileSync(path.join(srcDir, f), "utf8").replace(/\s+$/, ""))
    .join("\n\n");

  // The release notes used to be a <script> ahead of the app on every open, 150 KB read
  // on one page. The app now needs two things from them up front -- the newest version,
  // and where to fetch the notes when that page is opened -- and both are stamped here.
  const releases = fs.readFileSync(path.join(root, "public", "releases.js"), "utf8");
  const { version: appVersion, src: releasesSrc } = releaseStamp(releases);
  const bundle = `(function(){\n"use strict";\n` +
    `// Stamped by build.js from public/releases.js: the newest release, and the address the\n` +
    `// What's new page loads the notes from. Do not edit here.\n` +
    `const APP_VERSION="${appVersion}", RELEASES_SRC="${releasesSrc}";\n${body}\n})();\n`;
  fs.writeFileSync(path.join(root, "public", "app.js"), bundle);
  const guide = writeGuide(root);

  const css = fs.readFileSync(path.join(root, "public", "app.css"), "utf8");
  const hash = sha(bundle + css);

  const indexPath = path.join(root, "public", "index.html");
  let html = fs.readFileSync(indexPath, "utf8");
  const before = html;
  html = html.replace(/(href="\/app\.css)(\?b=[0-9a-f]+)?"/, `$1?b=${hash}"`);
  html = html.replace(/(src="\/app\.js)(\?b=[0-9a-f]+)?"/, `$1?b=${hash}"`);
  for (const need of ["/app.css?b=", "/app.js?b="]) {
    if (!html.includes(need)) throw new Error(`index.html is missing a tag for ${need}`);
  }
  if (/<script[^>]*src="\/releases\.js/.test(html)) {
    throw new Error("index.html loads releases.js up front; the app loads it on demand from RELEASES_SRC");
  }
  if (html !== before) fs.writeFileSync(indexPath, html);

  // After index.html, since the worker precaches "/" and its contents just moved.
  const version = stampServiceWorker(root);
  return { files: files.length, lines: bundle.split("\n").length, hash, version, appVersion, releasesSrc, guide };
}

/** What the bundle carries about the release notes: the newest entry's version and the
 *  cache-busted address of the file. The version is read off the first {v:'x.y'} entry,
 *  which is the newest since the file is kept newest-first (a test enforces the order). */
function releaseStamp(releases) {
  const m = releases.match(/\{v:'(\d+\.\d+)'/);
  if (!m) throw new Error("releases.js has no {v:'x.y'} entry to take the version from");
  return { version: m[1], src: `/releases.js?b=${sha(releases)}` };
}

if (require.main === module) {
  const r = build();
  console.log(`built public/app.js — ${r.files} files, ${r.lines} lines, build ${r.hash}, sw ${r.version}, guide ${r.guide} chars`);
}

module.exports = { build, shellFiles, shellVersion, stampServiceWorker, releaseStamp, sha, htmlToText, writeGuide };
